const DICTS = { en, es, fr, sw };
let current = 'en';

export function pickLang(hostLang) {
  const code = String(hostLang || '').slice(0, 2).toLowerCase();
  return DICTS[code] ? code : 'en';
}

export function setLang(code) {
  current = DICTS[code] ? code : 'en';
}

export const lang = () => current;

export function t(key, vars) {
  const text = DICTS[current][key] ?? en[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

export function tn(key, n) {
  const form = n === 1 ? 'one' : 'other';
  return t(`${key}_${form}`, { n: new Intl.NumberFormat(current).format(n) });
}

export const dictionaries = DICTS;
